#!/usr/bin/env python3
"""Renders every Noto Emoji code point into two-cell bitmaps for each cell size.

    python3 -I scripts/emoji2cells.py 'NotoEmoji[wght].ttf' ter-u12n.bdf > src/ui/fonts/emoji_cells.h

Needs Pillow and fontTools. The font is Noto Emoji (google/fonts ofl/notoemoji,
SIL OFL 1.1, see OFL-NotoEmoji.txt); download it and Terminus outside the repo.
The wide set is every code point Noto Emoji maps, less ASCII, what Terminus
(the BDF) already draws, the UI's aliased glyphs (glyph_set.h) and the
zero-width marks; the tray emoji (emoji_set.h) must be in it. It is written,
sorted, to lib/core/src/ui/emoji_wide.h. Each one is drawn one colour (Noto Emoji's weight axis at 700 for small cells, 500
for large) into a box two cells wide, then
split: the left half under the emoji's own code point, the right half under
kWideTailBase + its index. The halves use the CellFont layout, so the renderer
draws them like any other cell.
"""
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

UI_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "core", "src", "ui")
EMOJI_SET = os.path.join(UI_DIR, "emoji_set.h")
GLYPH_SET = os.path.join(UI_DIR, "glyph_set.h")
WIDE_OUT = os.path.join(UI_DIR, "emoji_wide.h")
# Zero width in text_width.cpp: ZWJ, variation selectors, the keycap mark,
# skin tone modifiers and tags.
ZERO_WIDTH = {0x200D, 0xFE0E, 0xFE0F, 0x20E3} | set(range(0x1F3FB, 0x1F400)) | set(range(0xE0000, 0xE0080))
SIZES = [(6, 12), (8, 14), (8, 16), (10, 18), (12, 24)]
BIG = 256


def style(h):
    """(weight, ink threshold): heavier and darker where thin strokes would vanish."""
    return (700, 80) if h <= 16 else (500, 100)


def emoji_set():
    src = open(EMOJI_SET).read()
    body = re.search(r"kTrayEmoji\[\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    cps = [int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]+", re.sub(r"//[^\n]*", "", body))]
    base = int(re.search(r"kWideTailBase\s*=\s*(0x[0-9A-Fa-f]+)", src).group(1), 16)
    return cps, base


def bdf_codepoints(path):
    return {int(l.split()[1]) for l in open(path, encoding="latin-1") if l.startswith("ENCODING")}


def aliased():
    body = re.search(r"kGlyphAliases\[\]\s*=\s*\{(.*?)\};", open(GLYPH_SET).read(), re.S).group(1)
    return {int(a, 16) for a in re.findall(r"\{\s*(0x[0-9A-Fa-f]+)\s*,", body)}


def master(font, cp):
    """The glyph at BIG px, cropped to its ink, as greyscale; None if blank."""
    img = Image.new("L", (BIG * 2, BIG * 2), 0)
    ImageDraw.Draw(img).text((BIG // 2, BIG // 2), chr(cp), font=font, fill=255)
    box = img.getbbox()
    return img.crop(box) if box else None


def write_wide(cps):
    with open(WIDE_OUT, "w") as f:
        f.write("#pragma once\n\n")
        f.write("// Every code point drawn as a two-cell emoji, sorted: Noto Emoji's, less\n")
        f.write("// what Terminus draws. The right half of kWideEmoji[i] is code point\n")
        f.write("// kWideTailBase + i. Generated by scripts/emoji2cells.py; do not edit.\n\n")
        f.write("namespace rc {\n\n")
        f.write("constexpr char32_t kWideEmoji[] = {\n")
        for i in range(0, len(cps), 8):
            f.write("    " + ", ".join("0x%05X" % cp for cp in cps[i:i + 8]) + ",\n")
        f.write("};\n\n}  // namespace rc\n")


def cells(glyph, w, h, threshold):
    """The two halves of a (2w x h) one-bit image, as CellFont rows."""
    side = min(2 * w, h)
    gw, gh = glyph.size
    scale = side / max(gw, gh)
    small = glyph.resize((max(1, round(gw * scale)), max(1, round(gh * scale))), Image.LANCZOS)
    canvas = Image.new("L", (2 * w, h), 0)
    canvas.paste(small, ((2 * w - small.width) // 2, (h - small.height) // 2))
    px = canvas.load()
    rb = (w + 7) // 8
    halves = []
    for x0 in (0, w):
        rows = []
        for y in range(h):
            bits = 0
            for x in range(w):
                if px[x0 + x, y] >= threshold:
                    bits |= 1 << (rb * 8 - 1 - x)
            rows += [(bits >> (8 * (rb - 1 - k))) & 0xFF for k in range(rb)]
        halves.append(rows)
    return halves


def main():
    font = ImageFont.truetype(sys.argv[1], BIG)
    from fontTools.ttLib import TTFont
    tray, base = emoji_set()
    skip = bdf_codepoints(sys.argv[2]) | aliased() | ZERO_WIDTH
    cmap = TTFont(sys.argv[1]).getBestCmap()
    cps = sorted(cp for cp in cmap if cp >= 0x80 and cp not in skip)
    masters = {}
    for weight in sorted({style(h)[0] for _, h in SIZES}):
        font.set_variation_by_axes([weight])
        masters[weight] = {cp: master(font, cp) for cp in cps}
    cps = [cp for cp in cps if all(m[cp] is not None for m in masters.values())]
    missing = [cp for cp in tray if cp not in cps]
    if missing:
        sys.exit("tray emoji not drawable: " + " ".join("U+%04X" % cp for cp in missing))
    write_wide(cps)
    print("#pragma once\n")
    print("// The wide emoji (lib/core/src/ui/emoji_wide.h) as two-cell halves for each")
    print("// cell size. Rendered from Noto Emoji, Copyright 2013 Google LLC, under the")
    print("// SIL Open Font License 1.1 (see OFL-NotoEmoji.txt). Generated by")
    print("// scripts/emoji2cells.py; do not edit.\n")
    print('#include "cell_font.h"')
    print('#include "ui/text_width.h"\n')
    print("namespace rc {\n")
    names = []
    for w, h in SIZES:
        name = "emoji%dx%d" % (w, h)
        names.append((name, w, h))
        weight, threshold = style(h)
        table = []
        for i, cp in enumerate(cps):
            g = masters[weight][cp]
            left, right = cells(g, w, h, threshold)
            table.append((cp, left))
            table.append((base + i, right))
        table.sort()
        print("inline constexpr uint32_t %sCodepoints[] = {" % name)
        for i in range(0, len(table), 8):
            print("    " + ", ".join("0x%05X" % cp for cp, _ in table[i:i + 8]) + ",")
        print("};\n")
        print("inline constexpr uint8_t %sBitmaps[] = {" % name)
        for cp, rows in table:
            print("    " + ", ".join("0x%02X" % b for b in rows) + ",  // U+%05X" % cp)
        print("};\n")
        print("inline constexpr CellFont %s = {%d, %d, %d, %sCodepoints, %sBitmaps};\n"
              % (name, w, h, len(table), name, name))
    print("// The emoji halves sized for f, or nullptr.")
    print("inline const CellFont* emojiCellsFor(const CellFont& f) {")
    for name, w, h in names:
        print("  if (f.w == %d && f.h == %d) return &%s;" % (w, h, name))
    print("  return nullptr;")
    print("}\n")
    print("// The bitmap for cp in font f: wide emoji halves from the matching emoji")
    print("// table, everything else through glyphFor.")
    print("inline const uint8_t* cellGlyph(const CellFont& f, char32_t cp) {")
    print("  if (emojiIndex(cp) >= 0 || isWideTail(cp))")
    print("    if (const CellFont* e = emojiCellsFor(f))")
    print("      if (const uint8_t* g = findGlyph(*e, cp)) return g;")
    print("  return glyphFor(f, cp);")
    print("}\n")
    print("}  // namespace rc")


main()
