"""Compiles site/mascots.json into src/web/mascot_presets.h for web config.

The browser flasher and the device's web config share one presets file
(spec docs/superpowers/specs/2026-10-31-cyberspace-fluffy-generator-design.md
§6), so they can't drift. Checks every preset against the limits in spec §2
and exits non-zero on a violation; Fluffy must be the first preset.

Runs as a PlatformIO pre: script on every build and rewrites the header only
when its content changes. Also runnable by hand:
python3 tools/gen_mascot_presets.py

Reads:  site/mascots.json
Writes: src/web/mascot_presets.h (gitignored)
"""
import json
import os
import sys

try:
    Import("env")  # noqa: F821 -- injected by PlatformIO
    PROJECT_DIR = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC_PATH = os.path.join(PROJECT_DIR, "site", "mascots.json")
DST_PATH = os.path.join(PROJECT_DIR, "src", "web", "mascot_presets.h")

ART_ROWS = 6        # rc::kMascotArtRows
ART_COLS = 13       # rc::kMascotArtCols
MAX_PHRASES = 10    # rc::kMascotMaxPhrases
PHRASE_MAX = 80     # rc::kMascotPhraseMax
DELIM = "MASCOT"


def fail(msg):
    sys.exit(f"{SRC_PATH}: {msg}")


def printable(s):
    return all(0x20 <= ord(c) <= 0x7E for c in s)


def check(data):
    presets = data.get("presets")
    if not isinstance(presets, list) or not presets:
        fail("no presets")
    if presets[0].get("name") != "Fluffy":
        fail("Fluffy must be the first preset")
    for p in presets:
        name = p.get("name")
        art = p.get("art")
        if not isinstance(name, str) or not name:
            fail("a preset has no name")
        if not isinstance(art, list) or not 1 <= len(art) <= ART_ROWS:
            fail(f"{name}: art must be 1 to {ART_ROWS} lines")
        for i, line in enumerate(art, 1):
            if not isinstance(line, str) or len(line) > ART_COLS or not printable(line):
                fail(f"{name}: art line {i} must be at most {ART_COLS} printable ASCII characters")
            if line != line.rstrip(" "):
                fail(f"{name}: art line {i} has trailing spaces")
    phrases = data.get("phrases")
    if not isinstance(phrases, list) or not 1 <= len(phrases) <= MAX_PHRASES:
        fail(f"phrases must be 1 to {MAX_PHRASES}")
    for i, s in enumerate(phrases, 1):
        if not isinstance(s, str) or not 1 <= len(s) <= PHRASE_MAX or not printable(s):
            fail(f"phrase {i} must be 1 to {PHRASE_MAX} printable ASCII characters")


def main():
    with open(SRC_PATH, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    check(data)
    minified = json.dumps(data, separators=(",", ":"), ensure_ascii=True)
    if f"){DELIM}" in minified:
        fail(f"contains the raw-string delimiter ){DELIM}")
    text = "\n".join([
        "// Generated by tools/gen_mascot_presets.py from site/mascots.json -- do not edit.",
        "#pragma once",
        "",
        f'constexpr const char* kMascotPresetsJson = R"{DELIM}({minified}){DELIM}";',
        "",
    ])
    old = None
    if os.path.isfile(DST_PATH):
        with open(DST_PATH, "r", encoding="utf-8") as fh:
            old = fh.read()
    if old != text:
        with open(DST_PATH, "w", encoding="utf-8") as fh:
            fh.write(text)
    print(f"mascot presets: {len(data['presets'])} presets, {len(data['phrases'])} phrases")


main()
