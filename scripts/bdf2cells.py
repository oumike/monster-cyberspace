#!/usr/bin/env python3
"""Converts a Terminus BDF to a fixed-cell CellFont header.

    python3 -I scripts/bdf2cells.py ter-u12n.bdf cell6x12 > src/ui/fonts/cell6x12.h

Emits 0x20-0x7E, 0xA0-0xFF and every code point in lib/core/src/ui/glyph_set.h,
each padded to the font bounding box, one byte per row (two when wider than
8 px), MSB first. Aliased
code points (kGlyphAliases) reuse their stand-in's bitmap. Terminus is under
the SIL OFL, whose Reserved Font Name clause is why the output is named
cell6x12/cell8x16, not Terminus.
"""
import os
import re
import sys

GLYPH_SET = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "core", "src",
                         "ui", "glyph_set.h")


def glyph_set():
    src = open(GLYPH_SET).read()
    extra = re.search(r"kExtraGlyphs\[\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    extra = re.sub(r"//[^\n]*", "", extra)
    cps = [int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]+", extra)]
    alias_src = re.search(r"kGlyphAliases\[\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    aliases = {int(a, 16): int(b, 16)
               for a, b in re.findall(r"\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}", alias_src)}
    return cps, aliases


def read_bdf(path):
    head, glyphs, cur, rows = {}, {}, None, None
    for line in open(path, encoding="latin-1"):
        w = line.split()
        if not w:
            continue
        if cur is None and w[0] in ("FONTBOUNDINGBOX",):
            head[w[0]] = [int(v) for v in w[1:5]]
        if w[0] == "ENCODING":
            cur = {"enc": int(w[1])}
        elif w[0] == "BBX" and cur is not None:
            cur["bbx"] = [int(v) for v in w[1:5]]
        elif w[0] == "BITMAP" and cur is not None:
            rows = []
        elif w[0] == "ENDCHAR":
            if cur is not None:
                cur["rows"] = rows
                glyphs[cur["enc"]] = cur
            cur, rows = None, None
        elif rows is not None:
            rows.append(w[0])
    return head["FONTBOUNDINGBOX"], glyphs


def cell_bitmap(g, fbb):
    fw, fh, fx, fy = fbb
    bw, bh, bx, by = g["bbx"]
    rb = (fw + 7) // 8
    out = [0] * (fh * rb)
    top = (fh + fy) - (by + bh)  # rows from the cell top
    for y, r in enumerate(g["rows"]):
        bits = int(r, 16)
        nbits = len(r) * 4
        for x in range(bw):
            if (bits >> (nbits - 1 - x)) & 1:
                cx, cy = x + bx - fx, top + y
                if 0 <= cx < fw and 0 <= cy < fh:
                    out[cy * rb + cx // 8] |= 0x80 >> (cx % 8)
    return out


def main():
    path, name = sys.argv[1], sys.argv[2]
    fbb, glyphs = read_bdf(path)
    fw, fh = fbb[0], fbb[1]
    if fw > 16:
        sys.exit("cells wider than 16 px are not supported")
    extra, aliases = glyph_set()
    wanted = sorted(set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | set(extra))
    table = []
    for cp in wanted:
        src = aliases.get(cp, cp) if cp not in glyphs else cp
        if src not in glyphs:
            sys.exit("missing glyph U+%04X and no alias" % cp)
        table.append((cp, cell_bitmap(glyphs[src], fbb)))

    print("#pragma once\n")
    print("// %s: %dx%d cells, %d glyphs." % (name, fw, fh, len(table)))
    print("// Derived from Terminus Font 4.49.1 %s, Copyright (C) 2020 Dimitar" % os.path.basename(path))
    print("// Toshkov Zhekov, under the SIL Open Font License 1.1 (see OFL-Terminus.txt).")
    print("// Subset and converted to fixed cells, so renamed per the licence's Reserved")
    print("// Font Name clause. Generated by scripts/bdf2cells.py; do not edit.\n")
    print('#include "cell_font.h"\n')
    print("namespace rc {\n")
    print("inline constexpr uint32_t %sCodepoints[] = {" % name)
    for i in range(0, len(table), 10):
        print("    " + ", ".join("0x%04X" % cp for cp, _ in table[i:i + 10]) + ",")
    print("};\n")
    print("inline constexpr uint8_t %sBitmaps[] = {" % name)
    for cp, rows in table:
        print("    " + ", ".join("0x%02X" % b for b in rows) + ",  // U+%04X" % cp)
    print("};\n")
    print("inline constexpr CellFont %s = {%d, %d, %d, %sCodepoints, %sBitmaps};\n"
          % (name, fw, fh, len(table), name, name))
    print("}  // namespace rc")


main()
